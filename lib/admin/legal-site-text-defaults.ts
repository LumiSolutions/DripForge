function buildLegalSectionFields(
  prefix: string,
  count: number,
  labelPrefix: string
) {
  const fields: { key: string; label: string; multiline?: boolean }[] = []
  for (let i = 1; i <= count; i += 1) {
    fields.push({
      key: `${prefix}_section_${i}_title`,
      label: `${labelPrefix} ${i} — Titel`,
    })
    fields.push({
      key: `${prefix}_section_${i}_body`,
      label: `${labelPrefix} ${i} — Inhalt`,
      multiline: true,
    })
  }
  return fields
}

function buildFaqFields(count: number) {
  const fields: { key: string; label: string; multiline?: boolean }[] = []
  for (let i = 1; i <= count; i += 1) {
    fields.push({ key: `faq_q${i}_question`, label: `FAQ ${i} — Frage` })
    fields.push({
      key: `faq_q${i}_answer`,
      label: `FAQ ${i} — Antwort`,
      multiline: true,
    })
  }
  return fields
}

